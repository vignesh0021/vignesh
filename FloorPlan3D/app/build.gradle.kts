// Release signing: resolved from (in priority order)
//  1. Environment variables (CI):    RELEASE_KEYSTORE_PATH / RELEASE_KEYSTORE_PASSWORD / RELEASE_KEY_ALIAS / RELEASE_KEY_PASSWORD
//  2. keystore.properties at repo project root (local developer machines)
//  3. Fallback to the debug signing config so `assembleRelease` never fails
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun signingValue(env: String, prop: String): String? =
    System.getenv(env) ?: keystoreProps.getProperty(prop)

val releaseStorePath = signingValue("RELEASE_KEYSTORE_PATH", "storeFile")
val releaseStoreFile = releaseStorePath?.let { rootProject.file(it) }?.takeIf { it.exists() }

